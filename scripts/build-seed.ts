// Generates the content seed (trimesters, subjects, concept bank, official decks) from the subject sources,
// plus supabase/setup.sql = schema + content, for pasting into the Supabase SQL editor in one go.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { BANK } from '../subjects/fvcs/concepts';
import { CARDS, DECK_NAME } from '../subjects/fvcs/cards';

const q = (s: string) => "'" + s.replace(/'/g, "''") + "'";
const arr = (a: string[]) => 'array[' + a.map(q).join(', ') + ']::text[]';

const TRIMESTERS = [{ id: 1, name: 'Trimester 1', sort: 1 }];
const SUBJECTS = [{ slug: 'fvcs', trimester: 1, name: 'Firm Value and Capital Structure', short: 'FVCS', sort: 1 }];
const DECKS = [{ id: '6b1c0f1e-6a43-4f0e-9d3c-0f5c2a9e7f01', subject: 'fvcs', name: DECK_NAME, cards: CARDS }];

const out: string[] = ['-- Generated by `npm run seed:sql`. Do not edit by hand.', ''];
for (const t of TRIMESTERS)
  out.push(`insert into public.trimesters (id, name, sort) values (${t.id}, ${q(t.name)}, ${t.sort}) on conflict (id) do nothing;`);
for (const s of SUBJECTS)
  out.push(`insert into public.subjects (slug, trimester_id, name, short_name, sort) values (${q(s.slug)}, ${s.trimester}, ${q(s.name)}, ${q(s.short)}, ${s.sort}) on conflict (slug) do update set name = excluded.name, short_name = excluded.short_name;`);
out.push('');

const rows: string[] = [];
for (const [topic, b] of Object.entries(BANK)) {
  for (const t of b.T) rows.push(`('fvcs', ${q(topic)}, 'T', ${q(t)}, null, null)`);
  for (const f of b.F) rows.push(`('fvcs', ${q(topic)}, 'F', ${q(f)}, null, null)`);
  for (const m of b.MC) rows.push(`('fvcs', ${q(topic)}, 'MC', ${q(m.q)}, ${arr(m.correct)}, ${arr(m.distractors)})`);
}
out.push('delete from public.concept_items where subject_slug = \'fvcs\';');
out.push('insert into public.concept_items (subject_slug, topic, kind, text, correct, distractors) values\n  ' + rows.join(',\n  ') + ';', '');

for (const d of DECKS) {
  out.push(`insert into public.decks (id, subject_slug, owner_id, name, source) values (${q(d.id)}, ${q(d.subject)}, null, ${q(d.name)}, 'official') on conflict (id) do update set name = excluded.name;`);
  out.push('insert into public.cards (deck_id, front, back, sort, ext_key) values\n  ' +
    d.cards.map((c, i) => `(${q(d.id)}, ${q(c.front)}, ${q(c.back)}, ${i}, ${q(c.key)})`).join(',\n  ') +
    '\non conflict (deck_id, ext_key) do update set front = excluded.front, back = excluded.back, sort = excluded.sort;', '');
}

const content = out.join('\n');
writeFileSync('supabase/migrations/20261025000100_content.sql', content);
const schema = readdirSync('supabase/migrations').filter(f => f.endsWith('.sql') && !f.includes('_content')).sort()
  .map(f => readFileSync('supabase/migrations/' + f, 'utf8')).join('\n');
writeFileSync('supabase/setup.sql', '-- Paste into the Supabase SQL editor and run once. Safe to re-run.\n\n' + schema + '\n' + content);
console.log(`concept rows: ${rows.length}, cards: ${DECKS.reduce((s, d) => s + d.cards.length, 0)}`);
